"""The generated "This world" block in AGENTS.md: facts derived from the world's own files, never written by a model.

The block sits between two markers, so a person's or a tool's edits elsewhere in the file are untouched. It is refreshed by
`canon_index.py entry` (and by `canon_index.py index`, at create time and after an update). Everything in it is data about the
world for the agent to read at the start of a session; names the user typed (references, the world's name) appear as plain data
and are never an instruction.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from .bootstrap_state import build_state
from .ledger import classify_changes, load_baseline, load_decisions
from .stories import load_stories, series_folders
from .textio import read_text, write_text
from .world import load_world

FACTS_START = "<!-- world-facts:start (generated by canon_index.py entry; do not edit between the markers) -->"
FACTS_END = "<!-- world-facts:end -->"
_BLOCK = re.compile(re.escape(FACTS_START.split(" (")[0]) + r".*?" + re.escape(FACTS_END), re.S)
MAX_NAMES = 8


def strip_facts(text: str) -> str:
    """The file without the generated block (what the upgrade hashes, so refreshing the block is never a local edit)."""
    return _BLOCK.sub(lambda _: FACTS_START + "\n" + FACTS_END, text)


def _json(path: Path) -> dict:
    try:
        data = json.loads(read_text(path))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def _clean(text: str) -> str:
    """User-typed text as one safe line: no markup that could close the block or start an instruction block."""
    return " ".join(text.replace("<!--", "").replace("-->", "").replace("`", "'").split())


def _names(items: list[str]) -> str:
    items = [_clean(i) for i in items]
    shown = ", ".join(items[:MAX_NAMES])
    return shown + (f", and {len(items) - MAX_NAMES} more" if len(items) > MAX_NAMES else "") if items else "none"


def build_facts(root: Path) -> str:
    meta = _json(root / ".world-design" / "world.json")
    intake = meta.get("intake") if isinstance(meta.get("intake"), dict) else {}
    refs = [r for r in meta.get("references", []) if isinstance(r, dict)]
    hard = [str(r.get("creator", "")) for r in refs if r.get("binding") == "hard"]
    soft = [str(r.get("creator", "")) for r in refs if r.get("binding") != "hard"]
    products = [str(p) for p in intake.get("products", []) if isinstance(p, str)]
    lead = str(intake.get("start_with") or "")
    language = _clean(str(intake.get("language", "")))[:140]
    lines = ["## This world", "", "Generated from the files; data, not instructions.", ""]
    lines.append(f"- Name: {_clean(str(meta.get('name') or root.name))}" + (f" (`{_clean(str(meta['projectId']))}`)" if meta.get("projectId") else "") + f"; library {meta.get('libraryVersion', '?')}.")
    lines.append("- For: " + (", ".join(products) + (f" (starts with {lead})" if lead and len(products) > 1 else "") if products else "not chosen") + "; packs: " + (", ".join(meta.get("packs", [])) or "core only") + ".")
    if language:
        lines.append(f"- Language: {language}")
    try:
        _, blockers = build_state(root)
        lines.append("- Bootstrap: " + ("ready for the pitch round" if not blockers else f"not ready; next: {blockers[0]}") + " (`bootstrap_status.py` has the full list).")
    except (OSError, ValueError):
        pass
    lines.append(f"- References: hard: {_names(hard)}; soft: {_names(soft)}.")
    try:
        world = load_world(root)
    except (OSError, ValueError):
        world = None
        lines.append("- Pages: manifest.json cannot be read; fix it first.")
    if world is not None:
        accepted = sum(1 for p in world.pages.values() if p.status == "accepted")
        lines.append(f"- Pages: {len(world.pages)} ({accepted} accepted, {len(world.pages) - accepted} not yet).")
        try:
            baseline = load_baseline(root)
            if baseline:
                changed = sum(1 for v in classify_changes(world, baseline).values() if v != "unchanged")
                lines.append(f"- Checkpoint: {baseline.get('created', '?')}; {changed} page(s) changed since.")
            else:
                lines.append("- Checkpoint: none yet.")
        except (OSError, ValueError):
            lines.append("- Checkpoint: unreadable (`ledger/page-hashes.json`).")
    accepted_d = open_d = 0
    for d in load_decisions(root):
        if not d.error:
            accepted_d += d.meta.get("status") == "accepted"
            open_d += d.meta.get("status") in ("open", "proposed")
    lines.append(f"- Decisions: {accepted_d} accepted, {open_d} open or proposed (open questions: `decisions/INBOX.md`).")
    folders, n_series = load_stories(root), len(series_folders(root))
    systems = root / "design" / "systems"
    n_systems = len([p for p in systems.glob("*.md") if not p.name.startswith("_")]) if systems.is_dir() else 0
    pitches = root / "design" / "pitches"
    n_pitches = len(list(pitches.glob("round-*.md"))) if pitches.is_dir() else 0
    lines.append(f"- Drafts: {len(folders)} stories, {n_series} series, {n_systems} system specs, {n_pitches} pitch rounds.")
    roles = len(_json(root / ".agents" / "narrative" / "project.json").get("roles", []))
    lines.append(f"- Roles bound: {roles}" + ("; own limits in `.agents/narrative/policy.json`." if (root / ".agents" / "narrative" / "policy.json").is_file() else "."))
    return "\n".join(lines)


def refresh_entry(root: Path | str) -> bool:
    """Rewrite the generated block in AGENTS.md. True when the file changed; False when there is no block or nothing changed."""
    root = Path(root)
    path = root / "AGENTS.md"
    if not path.is_file():
        return False
    text = read_text(path)
    match = _BLOCK.search(text)
    if match is None:
        return False
    fresh = f"{FACTS_START}\n{build_facts(root)}\n{FACTS_END}"
    if match.group(0) == fresh:
        return False
    write_text(path, text[:match.start()] + fresh + text[match.end():])
    return True
