"""The session summary: where the work stands, built by a tool from the files, never written by a model.

`ledger/last-session.md` is regenerated whenever the index is. It tells the next session (Claude Code or Codex) what
changed since the last approved checkpoint, which proposals and decisions are still open, and which stories are in
progress, so unintegrated work is neither redone nor contradicted. Deterministic: no timestamps, stable order.
"""

from __future__ import annotations

import re
from pathlib import Path

from .ledger import as_list, classify_changes, load_baseline, load_changes, load_decisions
from .stories import load_stories, open_invention_count
from .textio import read_text
from .world import World

SUMMARY_REL = "ledger/last-session.md"
_OPEN_DECISION = ("open", "proposed")
_STALE_OPEN = re.compile(r"^- \[ \] (\S+) -> (\S+)$")


def story_lines(root: Path) -> list[str]:
    """One line per story that is not final, with how many inventions are still open (the stories in progress)."""
    return [f"- `{story.slug}` (draft): {open_invention_count(story.path)} invention(s) still open" for story in load_stories(root) if not story.is_final]


def build_session_summary(world: World) -> str:
    root = world.root
    lines = ["# Where we left off", "",
             "<!-- Generated by tools/canon_index.py (summary, index); do not edit. Built from the ledger and decisions, not written by a model. -->", ""]

    baseline = None
    try:
        baseline = load_baseline(root)
    except (OSError, ValueError):
        pass
    changes = classify_changes(world, baseline)
    moved = {f: k for f, k in changes.items() if k != "unchanged"}
    lines.append("## Pages changed since the last approved checkpoint")
    if baseline is None:
        lines.append(f"- No checkpoint (`snapshot`) yet: all {len(world.pages)} pages count as new.")
    elif not moved:
        lines.append("- None.")
    else:
        for file, kind in sorted(moved.items()):
            page = world.pages.get(file)
            tag = " (protected)" if page is not None and world.is_protected(page) else ""
            lines.append(f"- `{file}`: {kind}{tag}")

    lines += ["", "## Proposals not yet accepted (change records)"]
    records = [r for r in load_changes(root) if not r.error and str(r.meta.get("status", "")) in ("proposed", "integrated")]
    for r in records:
        pages = ", ".join(as_list(r.meta.get("pages"))) or "-"
        lines.append(f"- `{r.meta.get('id', r.path)}` ({r.meta.get('tier', '?')}, {r.meta.get('status')}): {pages}")
    if not records:
        lines.append("- None.")

    lines += ["", "## Decisions waiting for the user"]
    waiting = [d for d in load_decisions(root) if not d.error and str(d.meta.get("status", "")) in _OPEN_DECISION]
    for d in waiting:
        block = " [blocking]" if d.meta.get("blocking") is True else ""
        lines.append(f"- `{d.meta.get('id', d.path)}` ({d.meta.get('status')}){block}: affects {', '.join(as_list(d.meta.get('affects'))) or '-'}")
    if not waiting:
        lines.append("- None.")

    stale = root / "ledger" / "stale.md"
    open_items = [m.groups() for m in map(_STALE_OPEN.match, read_text(stale).split("\n")) if m] if stale.is_file() else []
    lines += ["", "## Dependents still to check (`ledger/stale.md`)"]
    lines += [f"- `{a}` changed; check `{b}`" for a, b in open_items] or ["- None."]

    stories = story_lines(root)
    lines += ["", "## Stories in progress"] + (stories or ["- None."])

    log = root / "ledger" / "log.md"
    entries = [l for l in read_text(log).split("\n") if re.match(r"^\d{4}-\d{2}-\d{2} \|", l)] if log.is_file() else []
    lines += ["", "## Latest invention log lines"] + ([f"- {e}" for e in entries[-5:]] or ["- None."])
    return "\n".join(lines) + "\n"
