"""Validate the portable role registry and render provider-specific definitions.

Port of the retired Node generator (kept in evals/baselines/library-v0/scripts). Output was proved
byte-identical to it for LF sources against the committed adapters before the contract rewrite.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import Any

from .textio import js_trim

# The header every generated adapter starts with. Older headers stay recognizable (so a regenerate
# may overwrite them) but are never emitted. Each older header names the folder it told people to edit.
GENERATED = "Generated by tools/sync.py"
PREVIOUS_MARKERS = (
    ("Generated by scripts/sync.ts", "agents/"),
    ("Generated by tools/narrative-agents/sync.ts", ".agents/narrative"),
)
EDIT_SOURCE = "agents/"

_ID_RE = re.compile(r"^[a-z][a-z0-9-]{0,47}$")
_SKILL_RE = re.compile(r"^design-[a-z0-9-]+$")
PACKS = ("core", "live-game", "game")
TIERS = ("strong", "standard")


@dataclass(frozen=True)
class Profile:
    id: str
    name: str
    description: str
    mode: str  # "specialist" | "reviewer"
    skills: tuple[str, ...]
    path: str
    pack: str = "core"
    tier: str = "standard"


def native_name(profile_id: str) -> str:
    return profile_id if profile_id.startswith("narrative-") else f"narrative-{profile_id}"


def _marker_sources() -> list[tuple[str, str]]:
    return [(GENERATED, EDIT_SOURCE), *PREVIOUS_MARKERS]


def generated_adapter(path: str, content: str) -> bool:
    """True only when the file starts with the generator header (content is LF-normalized).

    An incidental mention of the marker elsewhere does not authorize overwriting a file.
    """
    pairs = _marker_sources()
    if path.endswith(".toml"):
        return any(content.startswith(f"# {m}; edit {src} instead.\n") for m, src in pairs)
    if not content.startswith("---\n"):
        return False
    close = content.find("\n---\n", 4)
    if close < 0:
        return False
    rest = content[close + 5 :]
    return any(rest.startswith(f"\n<!-- {m}; edit {src} instead. -->\n\n") for m, src in pairs)


def parse_registry(value: Any) -> list[Profile]:
    """Reject unsafe paths and duplicate identities/skill ownership before writing."""
    if (
        not isinstance(value, dict)
        or value.get("version") != 1
        or not isinstance(value.get("profiles"), list)
        or not value["profiles"]
    ):
        raise ValueError("Narrative registry needs version 1 and a non-empty profiles array")
    ids: set[str] = set()
    native_ids: set[str] = set()
    skills: set[str] = set()
    result: list[Profile] = []
    for item in value["profiles"]:
        if not isinstance(item, dict):
            raise ValueError("Narrative profile must be an object")
        pid, name, description = item.get("id"), item.get("name"), item.get("description")
        mode, path, item_skills = item.get("mode"), item.get("path"), item.get("skills")
        if (
            not isinstance(pid, str)
            or not _ID_RE.match(pid)
            or pid in ids
            or native_name(pid) in native_ids
            or not isinstance(name, str)
            or not name.strip()
            or not isinstance(description, str)
            or not description.strip()
            or len(description) > 300
            or mode not in ("specialist", "reviewer")
            or path != f"roles/{pid}.md"
            or not isinstance(item_skills, list)
            or not item_skills
            or item.get("pack", "core") not in PACKS
            or item.get("tier", "standard") not in TIERS
        ):
            raise ValueError(f"Invalid narrative profile identity, fields or path: {pid}")
        ids.add(pid)
        native_ids.add(native_name(pid))
        selected: list[str] = []
        for skill in item_skills:
            if not isinstance(skill, str) or not _SKILL_RE.match(skill) or skill in skills:
                raise ValueError(f"Invalid or repeated narrative skill ownership: {skill}")
            skills.add(skill)
            selected.append(skill)
        result.append(Profile(pid, name, description, mode, tuple(selected), path, item.get("pack", "core"), item.get("tier", "standard")))
    return result


def profile_prompt(profile: Profile, contract: str, role: str) -> str:
    if not js_trim(contract) or not js_trim(role):
        raise ValueError(f"Empty narrative contract or role: {profile.id}")
    paths = [f"- skills/{skill}/SKILL.md" for skill in profile.skills]
    parts = [
        js_trim(contract),
        js_trim(role),
        "## Base skill entrypoints",
        "These are reusable base skills. Read the relevant entrypoint before its procedure; add the current "
        "world's required project skills through its manifest/context packet.",
        "\n".join(paths),
    ]
    return "\n\n".join(parts) + "\n"


def _js_json(value: str) -> str:
    """JSON string literal matching JavaScript's JSON.stringify for strings."""
    return json.dumps(value, ensure_ascii=False)


def resolve_model(models: dict, override: dict | None, provider: str, tier: str) -> str | None:
    """The model for a tier: the project override wins over the library default; null/absent means inherit."""
    for source in (override or {}, models):
        value = (source.get(provider) or {}).get(tier)
        if value:
            if not isinstance(value, str) or not re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$", value):
                raise ValueError(f"Invalid model name for {provider}/{tier}: {value!r}")
            return value
    return None


EFFORTS = {"claude": ("low", "medium", "high", "xhigh", "max"), "codex": ("low", "medium", "high", "xhigh")}


def resolve_effort(models: dict, override: dict | None, provider: str, tier: str, role: str) -> str | None:
    """Reasoning effort for a role: the project's role entry, the project's tier entry, the library's role entry, the
    library's tier entry; null/absent means inherit the session's."""
    for source in (override or {}, models):
        effort = source.get("effort") or {}
        for value in ((effort.get("roles") or {}).get(role), (effort.get(provider) or {}).get(tier)):
            if value:
                if value not in EFFORTS[provider]:
                    raise ValueError(f"Invalid effort for {provider}/{role or tier}: {value!r}; use one of {', '.join(EFFORTS[provider])}")
                return value
    return None


def codex_definition(profile: Profile, prompt: str, model: str | None = None, effort: str | None = None) -> str:
    """JSON escaping is valid for the scalar TOML basic strings emitted here."""
    rows = [
        f"# {GENERATED}; edit {EDIT_SOURCE} instead.",
        f"name = {_js_json(native_name(profile.id))}",
        f"description = {_js_json(profile.description)}",
    ]
    if model:
        rows.append(f"model = {_js_json(model)}")
    if effort:
        rows.append(f"model_reasoning_effort = {_js_json(effort)}")
    if profile.mode == "reviewer":
        rows.append('sandbox_mode = "read-only"')
    rows.append(f"developer_instructions = {_js_json(prompt)}")
    return "\n".join(rows) + "\n"


def claude_definition(profile: Profile, prompt: str, model: str | None = None, preload_skills: bool = False,
                      effort: str | None = None) -> str:
    rows = [
        "---",
        f"name: {_js_json(native_name(profile.id))}",
        f"description: {_js_json(profile.description)}",
    ]
    if model:
        rows.append(f"model: {model}")
    if effort:
        rows.append(f"effort: {effort}")
    if preload_skills:
        rows.append("skills:")
        rows += [f"  - {skill}" for skill in profile.skills]
    if profile.mode == "reviewer":
        rows.append("tools: Read, Grep, Glob, WebFetch, WebSearch")
    rows += ["---", "", f"<!-- {GENERATED}; edit {EDIT_SOURCE} instead. -->", "", js_trim(prompt), ""]
    return "\n".join(rows)
